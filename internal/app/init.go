// InitRequest is `lmmtfy init` as asked on the command line.
type InitRequest struct {
	Name        string // program name
	Input       string
	Output      string
	MappingName string // "" = derived from the input file name
	Force       bool   // overwrite an existing output
	Detect      detect.Options
	Stdout      io.Writer
	Stderr      io.Writer
}

// Init detects the format of an input file and writes a draft, standalone
// mapping for it. It returns the process exit code.
func Init(req InitRequest) int {
	fail := func(code int, format string, args ...any) int {
		fmt.Fprintf(req.Stderr, "%s: %s\n", req.Name, fmt.Sprintf(format, args...))
		return code
	}
	if _, err := os.Stat(req.Output); err == nil && !req.Force {
		return fail(exitcode.Usage, "%s already exists (use --force to overwrite)", req.Output)
	} else if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return fail(exitcode.IO, "%v", err)
	}

	res, code := runDetect(req.Name, req.Input, req.Detect, req.Stderr)
	if res == nil {
		return code
	}
	name := req.MappingName
	if name == "" {
		base := filepath.Base(req.Input)
		name = detect.TargetName(strings.TrimSuffix(base, filepath.Ext(base)), 1)
	}

	data, err := RenderMapping(name, filepath.Base(req.Input), res)
	if err != nil {
		return fail(exitcode.IO, "%v", err)
	}
	// The draft must be a valid mapping: check it the way convert will.
	m, err := config.ParseMapping(data)
	if err != nil {
		return fail(exitcode.IO, "generated mapping does not load (this is a bug): %v", err)
	}
	m.ApplyDefaults()
	if plan, issues := engine.Compile(m); plan == nil {
		return fail(exitcode.IO, "generated mapping is invalid (this is a bug): %v", issues.Err())
	}

	if err := os.WriteFile(req.Output, data, 0o644); err != nil {
		return fail(exitcode.IO, "%v", err)
	}
	review := 0
	for _, c := range res.Columns {
		if len(c.Notes) > 0 || len(c.Failing) > 0 {
			review++
		}
	}
	fmt.Fprintf(req.Stdout, "wrote %s: mapping %s, %d columns", req.Output, name, len(res.Columns))
	if review > 0 {
		fmt.Fprintf(req.Stdout, ", %d to review (see comments)", review)
	}
	fmt.Fprintf(req.Stdout, "\nnext: edit the target names, types and output format, then run\n  %s convert %s --mapping %s -o <output.csv>\n", req.Name, req.Input, req.Output)
	return exitcode.OK
}

// mappingDoc mirrors config.Mapping with columns as an ordered list, so the
// generated file lists rules in the same order as the target columns.
type mappingDoc struct {
	Version     int            `yaml:"version"`
	Name        string         `yaml:"name"`
	Description string         `yaml:"description,omitempty"`
	Target      *config.Target `yaml:"target"`
	Input       config.Input   `yaml:"input"`
	OnError     config.OnError `yaml:"on_error"`
	Columns     yaml.MapSlice  `yaml:"columns"`
}

// RenderMapping builds a standalone mapping from a detection result: an
// inline target with normalized output (UTF-8, ISO dates, "." decimals), and
// one rule per source column, commented with what detection saw.
func RenderMapping(name, inputName string, res *detect.Result) ([]byte, error) {
	header := res.Header
	doc := mappingDoc{
		Version:     config.Version,
		Name:        name,
		Description: "Draft generated by lmmtfy init from " + inputName,
		Target: &config.Target{
			Output: config.Output{Encoding: "utf-8", Delimiter: ",", LineEnding: "crlf"},
		},
		Input: config.Input{
			Encoding:   res.Encoding,
			Delimiter:  config.Scalar(delimiterAlias(res.Delimiter)),
			SkipFooter: res.SkipFooter,
			Trim:       res.Trim,
		},
		OnError: config.OnError{Strategy: "fail_file", RejectFile: ptr(true)},
	}
	in := &doc.Input
	if !header {
		in.Header = &header
	}
	if res.HeaderRow > 1 {
		in.HeaderRow = res.HeaderRow
	}
	for _, tok := range res.NullTokens {
		in.NullTokens = append(in.NullTokens, config.Scalar(tok))
	}
	if res.RaggedRows != "error" {
		in.RaggedRows = res.RaggedRows
	}
	if res.DuplicateHeaders {
		in.DuplicateHeaders = "suffix"
	}
	if res.Escape != "double" {
		in.Escape = res.Escape
	}

	comments := yaml.CommentMap{}
	for _, c := range res.Columns {
		doc.Target.Columns = append(doc.Target.Columns, c.TargetColumn())

		rule := c.Rule()
		if header {
			source := config.Scalar(c.Name)
			rule.Source = &source
		} else {
			rule.SourceIndex = c.Index
		}
		doc.Columns = append(doc.Columns, yaml.MapItem{Key: c.Target, Value: rule})

		lines := []string{" " + describe(c)}
		if len(c.Failing) > 0 {
			lines = append(lines, " REVIEW: rejected values: "+quoteList(c.Failing))
		}
		for _, n := range c.Notes {
			lines = append(lines, " REVIEW: "+n)
		}
		comments["$.columns."+c.Target] = []*yaml.Comment{yaml.HeadComment(lines...)}
	}
	if len(res.Notes) > 0 {
		var lines []string
		for _, n := range res.Notes {
			lines = append(lines, " REVIEW: "+n)
		}
		comments["$.input"] = []*yaml.Comment{yaml.HeadComment(lines...)}
	}

	body, err := yaml.MarshalWithOptions(doc, yaml.WithComment(comments), yaml.UseLiteralStyleIfMultiline(true))
	if err != nil {
		return nil, err
	}
	head := "# Draft mapping generated by lmmtfy init from " + inputName + ".\n" +
		"# Review it before use: target column names and types, and the target\n" +
		"# output format, which must match the software that reads the files.\n"
	return append([]byte(head), body...), nil
}

func describe(c detect.Column) string {
	s := fmt.Sprintf("%s, %.0f%% of %d values", c.Type, c.Confidence*100, c.Values)
	if d := details(c); d != "" {
		s += ", " + d
	}
	if len(c.Examples) > 0 {
		s += ", e.g. " + quoteList(shortList(c.Examples))
	}
	return s
}

func delimiterAlias(d string) string {
	switch d {
	case "\t":
		return "tab"
	case " ":
		return "space"
	}
	return d
}

func ptr[T any](v T) *T { return &v }
